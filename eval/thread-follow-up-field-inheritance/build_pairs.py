def main() -> None:
    groups: dict[tuple[str, str], int] = defaultdict(int)
    rows = []
    seen = set()
    for n, (category, lang, prev, question, code) in enumerate(PAIRS, 1):
        assert len(code) == len(FIELDS) and set(code) <= set(CODE), (n, code)
        assert lang in {"en", "fr", "mixed"}, n
        assert (prev, question) not in seen, (n, question)
        seen.add((prev, question))
        position = groups[category, lang]
        groups[category, lang] += 1
        held = category != "target" and position % 5 in {1, 3}
        rows.append(
            {
                "id": f"{category}-{lang}-{position + 1:02d}",
                "lang": lang,
                "split": "heldout" if held else "dev",
                "prev_question": prev,
                "question": question,
                "category": category,
                "gold": {f: CODE[c] for f, c in zip(FIELDS, code, strict=True)},
            }
        )
    out = HERE / "pairs.jsonl"
    out.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), "utf-8")
    held = sum(r["split"] == "heldout" for r in rows)
    print(f"{len(rows)} pairs, {len(rows) - held} dev, {held} heldout -> {out}")


